// Feeds a frame to the extractor in two reads split at `split` and returns the
// MTData2 packet counters that came out.
std::vector<int> decodeSplit(const uint8_t* frame, size_t size, size_t split)
{
	auto protocol = std::make_shared<MtProtocol>();
	MessageExtractor extractor(protocol);
	std::deque<XsMessage> messages;
	std::vector<int> counters;

	for (int part = 0; part < 2; ++part)
	{
		const size_t offset = part ? split : 0;
		const size_t length = part ? size - split : split;
		XsByteArray raw(length, frame + offset);
		messages.clear();
		extractor.processNewData(nullptr, raw, messages);
		for (const auto& message : messages)
		{
			if (message.getMessageId() == 0x36)
			{
				XsDataPacket packet(&message);
				counters.push_back(packet.packetCounter());
			}
		}
	}
	return counters;
}

void expectEverySplitDecodes(const uint8_t* frame, size_t size, int expectedCounter)
{
	for (size_t split = 1; split < size; ++split)
	{
		const std::vector<int> counters = decodeSplit(frame, size, split);
		ASSERT_EQ(counters.size(), 1u) << "frame lost or duplicated at split " << split;
		EXPECT_EQ(counters[0], expectedCounter) << "wrong packet at split " << split;
	}
}

// Decodes a repeated stream in fixed-size reads and counts MTData2 messages.
int decodeStream(const uint8_t* frame, size_t size, int repeats, size_t chunk)
{
	std::vector<uint8_t> stream;
	for (int i = 0; i < repeats; ++i)
		stream.insert(stream.end(), frame, frame + size);

	auto protocol = std::make_shared<MtProtocol>();
	MessageExtractor extractor(protocol);
	std::deque<XsMessage> messages;
	int decoded = 0;
	for (size_t offset = 0; offset < stream.size(); offset += chunk)
	{
		const size_t length = std::min(chunk, stream.size() - offset);
		XsByteArray raw(length, stream.data() + offset);
		messages.clear();
		extractor.processNewData(nullptr, raw, messages);
		for (const auto& message : messages)
			decoded += (message.getMessageId() == 0x36);
	}
	return decoded;
}

