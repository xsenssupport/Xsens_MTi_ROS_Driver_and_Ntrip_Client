// A complete frame split across two reads must always decode exactly once,
// whatever the boundary. Unfixed, the customer frame is lost at splits 135-158.
TEST(MessageExtractorFraming, CustomerFrameSurvivesEveryReadBoundary)
{
	expectEverySplitDecodes(CUSTOMER_FRAME_17014, sizeof(CUSTOMER_FRAME_17014), 17014);
}

TEST(MessageExtractorFraming, CapturedFramesSurviveEveryReadBoundary)
{
	expectEverySplitDecodes(CAPTURED_FRAME_1, sizeof(CAPTURED_FRAME_1), 2488);
	expectEverySplitDecodes(CAPTURED_FRAME_2, sizeof(CAPTURED_FRAME_2), 3827);
	expectEverySplitDecodes(CAPTURED_FRAME_3, sizeof(CAPTURED_FRAME_3), 8375);
}

// Continuous streaming at read sizes a serial port actually produces. Unfixed,
// a 32-byte read decoded only 8 of 32 frames.
TEST(MessageExtractorFraming, StreamLosesNoFrameAtAnyReadSize)
{
	const size_t chunks[] = {32, 62, 64, 128, 159, 184, 256, 496, 8192};
	for (size_t chunk : chunks)
		EXPECT_EQ(decodeStream(CUSTOMER_FRAME_17014, sizeof(CUSTOMER_FRAME_17014), 32, chunk), 32)
			<< "frames lost with " << chunk << "-byte reads";
}

// The fix must not keep invalid data alive: a complete rejected frame with no
// preceding partial message is still discarded, and the next real frame decodes
// immediately.
TEST(MessageExtractorFraming, RejectedFrameWithNoPartialIsDiscarded)
{
	std::vector<uint8_t> stream = {0xfa, 0x31, 0xbd, 0x00, 0x12};  // valid checksum, invalid bus id
	stream.insert(stream.end(), CUSTOMER_FRAME_17014,
		CUSTOMER_FRAME_17014 + sizeof(CUSTOMER_FRAME_17014));

	auto protocol = std::make_shared<MtProtocol>();
	MessageExtractor extractor(protocol);
	std::deque<XsMessage> messages;
	XsByteArray raw(stream.size(), stream.data());
	extractor.processNewData(nullptr, raw, messages);

	ASSERT_EQ(messages.size(), 1u);
	EXPECT_EQ(messages.front().getMessageId(), 0x36);
}
