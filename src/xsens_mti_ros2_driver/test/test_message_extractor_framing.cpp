// Mirrors the protocol manager the driver installs, including
// MtDevice::messageLooksSane: master (0xff) or bus 1 only.
class MtProtocol : public IProtocolManager
{
public:
	MessageLocation findMessage(XsProtocolType& type, const XsByteArray& raw) override
	{
		type = XPT_Xbus;
		return m_handler.findMessage(raw);
	}
	XsMessage convertToMessage(XsProtocolType&, MessageLocation& where, const XsByteArray& raw) override
	{
		return m_handler.convertToMessage(where, raw);
	}
	bool validateMessage(const XsMessage& message) const override
	{
		return message.getBusId() == 0xff || message.getBusId() == 1;
	}
private:
	ProtocolHandler m_handler;
};

