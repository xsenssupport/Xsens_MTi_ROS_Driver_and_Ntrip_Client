// Regression for a frame-loss defect in the vendored Xsens SDK.
//
// MessageExtractor::processNewData() rejects a candidate message whose checksum
// is valid but whose bus id is not, and used to drop the input buffer up to the
// end of that candidate. When the candidate is embedded in the payload of an
// earlier message that is still incomplete, this discarded the real message's
// first bytes, so a frame that arrived intact on the wire never reached the
// publishers. It fires only when a read boundary falls between the end of the
// embedded candidate and the end of the real frame.
//
// These are real MTData2 frames: one reported by a customer (MTi-320, packet
// counter 17014) and three captured independently from an MTi-320-3A-SK. All
// four carry a checksum-valid, invalid-bus-id sequence inside ordinary
// measurement data, so the condition arises without anything unusual on the bus.
//
// The SDK is vendored, so refreshing it can silently reintroduce this; that is
// what this test guards against.
#include <gtest/gtest.h>

#include <xscontroller/messageextractor.h>
#include <xscontroller/protocolhandler.h>
#include <xstypes/xsdatapacket.h>

#include <cstdint>
